"""Generate Crucible's flat feature names and Vulkan feature accesses."""

from __future__ import annotations

import argparse
import re
import sys
import xml.etree.ElementTree as ET
from collections import Counter, defaultdict
from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path
from typing import TypeAlias

from mako.template import Template

DEPENDENCY_TOKEN = re.compile(r'VK_\w+|[+(),]')
API_VERSION = re.compile(r'VK_(?:(?:BASE|COMPUTE|GRAPHICS)_)?VERSION_(\d+)_(\d+)')
FEATURE_SUFFIX = re.compile(r'Features([A-Z0-9]+)$')
AGGREGATE_FEATURES = re.compile(r'VkPhysicalDeviceVulkan\d+Features')
BANNER = '// Generated by misc/gen_features.py from include/vulkan/vk.xml.\n'

# These feature structs were not promoted; their core functionality is unconditional.
CORE_DEFAULTS = (
    ('texelBufferAlignment', '1.3'),
    ('extendedDynamicState', '1.3'),
    ('extendedDynamicState2', '1.3'),
)

FeatureKey: TypeAlias = tuple[str, str]


@dataclass(frozen=True, slots=True)
class FeatureMember:
    name: str
    field: str
    implicit_extension: str | None


@dataclass(frozen=True, slots=True)
class FeatureStructure:
    c_type: str
    s_type: str
    availability: tuple[str, ...]
    guards: tuple[str, ...]
    members: tuple[FeatureMember, ...]


@dataclass(frozen=True, slots=True)
class ImplicitFeature:
    name: str
    extension: str | None
    availability: str


@dataclass(frozen=True, slots=True)
class FeatureDescriptions:
    names: tuple[str, ...]
    implicit: tuple[ImplicitFeature, ...]
    structures: tuple[FeatureStructure, ...]

    def members(self, name: str) -> tuple[tuple[FeatureStructure, FeatureMember], ...]:
        return tuple((struct, member) for struct in self.structures
                     for member in struct.members if member.name == name)


def is_vulkan(element: ET.Element) -> bool:
    return 'vulkan' in element.get('api', 'vulkan').split(',')


def c_api_version(number: str) -> str:
    major, minor = number.split('.')
    return f'VK_MAKE_API_VERSION(0, {major}, {minor}, 0)'


def condition(expression: str | None) -> str:
    """Translate the registry's extension dependency expressions to C."""
    if not expression:
        return 'true'
    tokens = DEPENDENCY_TOKEN.findall(expression)
    if ''.join(tokens) != re.sub(r'\s+', '', expression):
        raise ValueError(f'Invalid dependency expression {expression!r}: unexpected character')
    pos = 0

    def error(message: str) -> ValueError:
        return ValueError(
            f'Invalid dependency expression {expression!r} at token {pos + 1}: {message}')

    def atom() -> str:
        nonlocal pos
        if pos == len(tokens) or tokens[pos] in ('+', ',', ')'):
            raise error('expected an extension, version, or "("')
        token = tokens[pos]
        pos += 1
        if token == '(':
            result = disjunction()
            if pos == len(tokens) or tokens[pos] != ')':
                raise error('expected ")"')
            pos += 1
            return result
        match = API_VERSION.fullmatch(token)
        if match:
            return f'(context->api_version >= {c_api_version(".".join(match.groups()))})'
        return f'cru_feature_has_extension(context, "{token}")'

    def conjunction() -> str:
        nonlocal pos
        parts = [atom()]
        while pos < len(tokens) and tokens[pos] == '+':
            pos += 1
            parts.append(atom())
        return '({})'.format(' && '.join(parts))

    def disjunction() -> str:
        nonlocal pos
        parts = [conjunction()]
        while pos < len(tokens) and tokens[pos] == ',':
            pos += 1
            parts.append(conjunction())
        return '({})'.format(' || '.join(parts))

    result = disjunction()
    if pos != len(tokens):
        raise error('expected "+" or ","')
    return result


def canonical_type(name: str, types: Mapping[str, ET.Element]) -> str:
    while name in types:
        alias = types[name].get('alias')
        if alias is None:
            break
        name = alias
    return name


def member_name(member: ET.Element) -> str:
    name = member.findtext('name')
    if name is None:
        raise ValueError('Feature member has no name')
    return name


def member_alias(member: ET.Element) -> str | None:
    name = member.find('name')
    assert name is not None
    return name.get('alias')


def feature_root(parents: Mapping[FeatureKey, FeatureKey], key: FeatureKey) -> FeatureKey:
    while parents[key] != key:
        key = parents[key]
    return key


def collect_feature_names(
    structures: Mapping[str, list[ET.Element]],
    types: Mapping[str, ET.Element],
) -> tuple[dict[FeatureKey, FeatureKey], dict[FeatureKey, str]]:
    # The registry identifies aliases at both the structure and member levels.
    # Do not merge unrelated vendor features merely because their names match.
    parents: dict[FeatureKey, FeatureKey] = {
        (struct, member_name(member)): (struct, member_name(member))
        for struct, members in structures.items() for member in members
    }
    for struct, members in structures.items():
        for member in members:
            alias = member_alias(member)
            if alias and '::' in alias:
                other_struct, field = alias.split('::')
                other = (canonical_type(other_struct, types), field)
                if other not in parents:
                    raise ValueError(f'Unknown feature alias {alias} in {struct}')
                key = (struct, member_name(member))
                parents[feature_root(parents, key)] = feature_root(parents, other)

    groups: defaultdict[FeatureKey, list[ET.Element]] = defaultdict(list)
    for struct, members in structures.items():
        for member in members:
            groups[feature_root(parents, (struct, member_name(member)))].append(member)
    names: dict[FeatureKey, str] = {}
    for key, members in groups.items():
        links: set[str] = set()
        for member in members:
            link = member.get('featurelink')
            if link:
                links.add(link)
        if len(links) > 1:
            raise ValueError(f'Conflicting feature links for {key}: {sorted(links)}')
        names[key] = next(iter(links)) if links else key[1]
    counts = Counter(names.values())
    for key, name in names.items():
        if counts[name] > 1:
            suffix = FEATURE_SUFFIX.search(key[0])
            if suffix is None:
                raise ValueError(f'Cannot disambiguate feature {name} in {key[0]}')
            names[key] += suffix.group(1)
    duplicates = sorted(name for name, count in Counter(names.values()).items() if count > 1)
    if duplicates:
        raise ValueError(f'Duplicate feature names: {", ".join(duplicates)}')
    return parents, names


def structure_order(name: str) -> tuple[int, str]:
    # Prefer aggregates when legal. On older APIs use their individual aliases.
    if name == 'VkPhysicalDeviceFeatures':
        return 0, name
    if AGGREGATE_FEATURES.fullmatch(name):
        return 1, name
    return 2, name


def collect_features(registry: ET.Element) -> FeatureDescriptions:
    types: dict[str, ET.Element] = {}
    for element in registry.findall('./types/type'):
        name = element.get('name', element.findtext('name'))
        if is_vulkan(element) and name:
            types[name] = element

    # Each structure may be available through core and/or extension aliases.
    availability: defaultdict[str, set[str]] = defaultdict(set)
    guards: defaultdict[str, set[str | None]] = defaultdict(set)
    platforms = {p.attrib['name']: p.get('protect')
                 for p in registry.findall('./platforms/platform')}
    for core in registry.findall('./feature'):
        if not is_vulkan(core):
            continue
        for require in core.findall('require'):
            entries = require.findall('type')
            if not is_vulkan(require) or not entries:
                continue
            available = (f'(context->api_version >= {c_api_version(core.attrib["number"])} && '
                         f'{condition(require.get("depends"))})')
            for entry in entries:
                name = canonical_type(entry.attrib['name'], types)
                availability[name].add(available)
                guards[name].add(None)
    extension_conditions: dict[str, str] = {}
    for extension in registry.findall('./extensions/extension'):
        if 'vulkan' not in extension.get('supported', '').split(','):
            continue
        extension_name = extension.attrib['name']
        available = (f'cru_feature_has_extension(context, "{extension_name}") && '
                     f'{condition(extension.get("depends"))}')
        extension_conditions[extension_name] = f'({available})'
        guard = platforms.get(extension.get('platform', ''))
        if extension.get('provisional') == 'true':
            guard = 'VK_ENABLE_BETA_EXTENSIONS'
        for require in extension.findall('require'):
            entries = require.findall('type')
            if not is_vulkan(require) or not entries:
                continue
            required = f'({available} && {condition(require.get("depends"))})'
            for entry in entries:
                name = canonical_type(entry.attrib['name'], types)
                availability[name].add(required)
                guards[name].add(guard)

    structures: dict[str, list[ET.Element]] = {}
    for name, element in types.items():
        if element.get('alias') or not availability[name]:
            continue
        if name != 'VkPhysicalDeviceFeatures' and not {
                'VkPhysicalDeviceFeatures2', 'VkDeviceCreateInfo'
        }.issubset(element.get('structextends', '').split(',')):
            continue
        members = [m for m in element.findall('member')
                   if is_vulkan(m) and m.findtext('type') == 'VkBool32']
        if not members:
            continue
        if not all(m.findtext('type') in ('VkStructureType', 'void', 'VkBool32')
                   for m in element.findall('member') if is_vulkan(m)):
            raise ValueError(f'Unexpected member type in feature structure {name}')
        structures[name] = members

    parents, names = collect_feature_names(structures, types)
    fields = tuple(sorted(names.values()))
    implicit_extensions: dict[FeatureKey, str] = {}
    for struct, members in structures.items():
        for member in members:
            alias = member_alias(member) or ''
            if alias.startswith('VK_'):
                implicit_extensions[feature_root(parents, (struct, member_name(member)))] = alias
    # These extension-only promotions are not marked as member aliases.
    for struct, field, extension in [
        ('VkPhysicalDeviceShaderDrawParametersFeatures', 'shaderDrawParameters',
         'VK_KHR_shader_draw_parameters'),
        ('VkPhysicalDeviceVulkan14Features', 'pushDescriptor', 'VK_KHR_push_descriptor'),
    ]:
        implicit_extensions[feature_root(parents, (struct, field))] = extension
    implicit = [
        ImplicitFeature(name, extension, extension_conditions[extension])
        for name, extension in sorted((names[key], extension)
                                      for key, extension in implicit_extensions.items())
    ]
    implicit.extend(
        ImplicitFeature(name, None,
                        f'(context->api_version >= {c_api_version(version)})')
        for name, version in CORE_DEFAULTS
    )
    implicit.sort(key=lambda feature: feature.name)

    descriptions: list[FeatureStructure] = []
    for struct in sorted(structures, key=structure_order):
        if struct == 'VkPhysicalDeviceFeatures':
            c_type = 'VkPhysicalDeviceFeatures2'
            s_type = 'VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_FEATURES_2'
        else:
            c_type = struct
            s_type_member = types[struct].find("member[name='sType']")
            if s_type_member is None or 'values' not in s_type_member.attrib:
                raise ValueError(f'Missing sType value in {struct}')
            s_type = s_type_member.attrib['values']
        described_members: list[FeatureMember] = []
        for member in structures[struct]:
            field = member_name(member)
            key = feature_root(parents, (struct, field))
            if struct == 'VkPhysicalDeviceFeatures':
                field = 'features.' + field
            described_members.append(FeatureMember(
                names[key], field, implicit_extensions.get(key)))
        protections = guards[struct]
        protection_names = (() if None in protections else
                            tuple(sorted(p for p in protections if p is not None)))
        descriptions.append(FeatureStructure(c_type, s_type, tuple(sorted(availability[struct])),
                                             protection_names, tuple(described_members)))
    return FeatureDescriptions(fields, tuple(implicit), tuple(descriptions))


TEMPLATE_H = Template(BANNER + '''\
#pragma once

#include <stdbool.h>

struct cru_features {
% for name in features.names:
    bool ${name} : 1;
% endfor
};
''', strict_undefined=True)

TEMPLATE_C = Template(BANNER + '''\
#include "src/framework/test/t_features.h"

const size_t cru_feature_count = ${len(features.names)};

% for feature in features.implicit:
static bool
implicit_available_${feature.name}(const struct cru_feature_context *context)
{
    return ${feature.availability};
}

% endfor
% for struct in features.structures:
% if struct.guards:
#if ${' || '.join('defined({})'.format(guard) for guard in struct.guards)}
% endif
static bool
available_${struct.c_type}(const struct cru_feature_context *context)
{
    return ${' ||\\n           '.join(struct.availability)};
}

% if struct.guards:
#endif
% endif
% endfor
% for name in features.names:
static bool
require_${name}(struct cru_feature_setup *setup)
{
    (void)setup;
% for feature in features.implicit:
% if feature.name == name:
    if (implicit_available_${name}(setup->context))
        return true;
% endif
% endfor
% for struct, member in features.members(name):
% if struct.guards:
#if ${' || '.join('defined({})'.format(guard) for guard in struct.guards)}
% endif
    if (available_${struct.c_type}(setup->context)) {
        const struct cru_feature_state state = cru_require_feature_struct(
            setup, ${struct.s_type}, sizeof(${struct.c_type}));
        const ${struct.c_type} *supported = state.supported;
        ${struct.c_type} *enabled = state.enabled;
        cru_add_feature_requirement(setup, "${name}",
                                    &supported->${member.field}, &enabled->${member.field});
        return true;
    }
% if struct.guards:
#endif
% endif
% endfor
    return false;
}

% endfor
const char *
cru_select_features(struct cru_feature_setup *setup, const struct cru_features *required)
{
% for name in features.names:
    if (required->${name}) {
        setup->any = true;
        if (!require_${name}(setup))
            return "${name}";
    }
% endfor
    return NULL;
}

void
cru_preserve_implicit_features(const struct cru_feature_setup *setup)
{
    const struct cru_feature_context *context = setup->context;
% for struct in features.structures:
% if any(member.implicit_extension for member in struct.members):
% if struct.guards:
#if ${' || '.join('defined({})'.format(guard) for guard in struct.guards)}
% endif
    if (cru_find_feature_struct(&setup->supported, ${struct.s_type})) {
        ${struct.c_type} *node = cru_find_feature_struct(
            context->device_info->pNext, ${struct.s_type});
% for member in struct.members:
% if member.implicit_extension:
        if (cru_feature_has_extension(context, "${member.implicit_extension}"))
            node->${member.field} = VK_TRUE;
% endif
% endfor
    }
% if struct.guards:
#endif
% endif
% endif
% endfor
}

void
cru_record_enabled_features(const struct cru_feature_context *context,
                             struct cru_features *features)
{
    *features = (struct cru_features) {0};
    const VkPhysicalDeviceFeatures2 legacy = {
        .features = *context->device_info->pEnabledFeatures,
    };
% for feature in features.implicit:
    features->${feature.name} = implicit_available_${feature.name}(context);
% endfor
% for struct in features.structures:
% if struct.guards:
#if ${' || '.join('defined({})'.format(guard) for guard in struct.guards)}
% endif
    {
% if struct.c_type == 'VkPhysicalDeviceFeatures2':
        const ${struct.c_type} *node = &legacy;
% else:
        const ${struct.c_type} *node = cru_find_feature_struct(
            context->device_info->pNext, ${struct.s_type});
% endif
        if (node) {
% for member in struct.members:
            features->${member.name} |= node->${member.field} != VK_FALSE;
% endfor
        }
    }
% if struct.guards:
#endif
% endif
% endfor
}
''', strict_undefined=True)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('xml', type=Path)
    parser.add_argument('header', type=Path)
    parser.add_argument('source', type=Path)
    args = parser.parse_args()
    try:
        features = collect_features(ET.parse(args.xml).getroot())
        args.header.write_text(TEMPLATE_H.render(features=features), encoding='utf-8')
        args.source.write_text(TEMPLATE_C.render(features=features), encoding='utf-8')
    except (OSError, ET.ParseError, ValueError) as error:
        sys.exit(f'{parser.prog}: {error}')


if __name__ == '__main__':
    main()
